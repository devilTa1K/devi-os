# Generates src\auth_config.rs: a salted, iterated SHA-256 of your passphrase.
# The passphrase is never written to disk. Do not commit src\auth_config.rs.
$rounds = 20000
$secure = Read-Host "Choose a passphrase (12-64 printable ASCII characters)" -AsSecureString
$bstr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure)
$plain = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($bstr)
[Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr)
if ($plain.Length -lt 12 -or $plain.Length -gt 64) { "Passphrase must be 12-64 characters."; return }
if ($plain -notmatch '^[\x20-\x7e]+$') { "Printable ASCII only."; return }

$pass = [Text.Encoding]::ASCII.GetBytes($plain)
$plain = $null
$salt = New-Object byte[] 16
[Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($salt)
$sp = [byte[]]($salt + $pass)
$sha = [Security.Cryptography.SHA256]::Create()

# h = SHA256(salt || pass); then (rounds - 1) times: h = SHA256(h || salt || pass)
$h = $sha.ComputeHash($sp)
for ($i = 1; $i -lt $rounds; $i++) { $h = $sha.ComputeHash([byte[]]($h + $sp)) }

$saltList = ($salt | ForEach-Object { '0x{0:x2}' -f $_ }) -join ', '
$hashList = ($h | ForEach-Object { '0x{0:x2}' -f $_ }) -join ', '
$lines = @(
    '// Generated by setup-auth.ps1. Do not commit this file.',
    "pub const ROUNDS: u32 = $rounds;",
    "pub const SALT: [u8; 16] = [$saltList];",
    "pub const HASH: [u8; 32] = [$hashList];"
)
Set-Content -Encoding ascii src\auth_config.rs $lines
"Wrote src\auth_config.rs. The passphrase cannot be recovered, so remember it."
